package br.edu.pit.catalogo.dao;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Centraliza a criação de conexões JDBC e a criação inicial do banco.
 *
 * <p>Por padrão usa o H2 em arquivo (pasta {@code dados/}), que não precisa de instalação.
 * Para usar PostgreSQL, rode com as propriedades de sistema:
 * {@code -Dcatalogo.db.url=jdbc:postgresql://localhost:5432/catalogo
 *  -Dcatalogo.db.usuario=postgres -Dcatalogo.db.senha=suasenha
 *  -Dcatalogo.db.driver=org.postgresql.Driver}</p>
 */
public final class FabricaDeConexoes {

    private static final String URL_PADRAO = "jdbc:h2:file:./dados/catalogo";
    private static final String DRIVER_PADRAO = "org.h2.Driver";

    private FabricaDeConexoes() {
    }

    /**
     * Abre uma nova conexão com o banco configurado.
     *
     * @return conexão aberta (quem chama deve fechá-la, de preferência com try-with-resources)
     * @throws SQLException se não for possível conectar
     */
    public static Connection getConexao() throws SQLException {
        String driver = System.getProperty("catalogo.db.driver", DRIVER_PADRAO);
        try {
            // Registro explícito do driver: necessário em alguns servidores web
            Class.forName(driver);
        } catch (ClassNotFoundException e) {
            throw new SQLException("Driver JDBC não encontrado: " + driver, e);
        }
        String url = System.getProperty("catalogo.db.url", URL_PADRAO);
        String usuario = System.getProperty("catalogo.db.usuario", "sa");
        String senha = System.getProperty("catalogo.db.senha", "");
        return DriverManager.getConnection(url, usuario, senha);
    }

    /**
     * Cria as tabelas (se ainda não existirem) e insere dados de exemplo
     * quando o catálogo estiver vazio.
     *
     * <p>A tabela {@code usuario} existe apenas para demonstrar o risco de vazamento de
     * dados (confidencialidade) por SQL Injection: ela não é exibida em nenhuma tela.</p>
     *
     * @throws SQLException em caso de erro no banco
     */
    public static void inicializarBanco() throws SQLException {
        try (Connection conn = getConexao(); Statement st = conn.createStatement()) {
            st.execute("""
                CREATE TABLE IF NOT EXISTS item_midia (
                    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    titulo         VARCHAR(255) NOT NULL,
                    autor_diretor  VARCHAR(255),
                    ano_lancamento INT,
                    genero         VARCHAR(100),
                    sinopse        VARCHAR(2000),
                    tipo_midia     VARCHAR(50)  NOT NULL
                )""");
            st.execute("""
                CREATE TABLE IF NOT EXISTS usuario (
                    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    login      VARCHAR(100) NOT NULL UNIQUE,
                    senha_hash VARCHAR(255) NOT NULL
                )""");

            try (ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM item_midia")) {
                rs.next();
                if (rs.getInt(1) == 0) {
                    inserirDadosDeExemplo(conn);
                }
            }
        }
    }

    private static void inserirDadosDeExemplo(Connection conn) throws SQLException {
        try (Statement st = conn.createStatement()) {
            st.execute("""
                INSERT INTO item_midia (titulo, autor_diretor, ano_lancamento, genero, sinopse, tipo_midia) VALUES
                ('Dom Casmurro', 'Machado de Assis', 1899, 'Romance', 'Bentinho relembra sua vida e o ciúme de Capitu.', 'Livro'),
                ('O Alienista', 'Machado de Assis', 1882, 'Sátira', 'Um médico interna quase toda a cidade de Itaguaí.', 'Livro'),
                ('Vidas Secas', 'Graciliano Ramos', 1938, 'Romance', 'Uma família de retirantes enfrenta a seca no sertão.', 'Livro'),
                ('Central do Brasil', 'Walter Salles', 1998, 'Drama', 'Uma ex-professora ajuda um menino a procurar o pai.', 'Filme'),
                ('Cidade de Deus', 'Fernando Meirelles', 2002, 'Drama', 'O crescimento do crime em uma comunidade do Rio.', 'Filme')
                """);
            // Usuário fictício, criado só para a demonstração do vazamento
            st.execute("""
                INSERT INTO usuario (login, senha_hash) VALUES
                ('admin', '$2a$10$exemploDeHashFicticioParaDemonstracao')
                """);
        }
    }
}
